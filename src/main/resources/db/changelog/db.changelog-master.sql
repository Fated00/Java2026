--changeset autosalon:001-create-schema
CREATE TABLE app_users (
    id UUID PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    removed BOOLEAN NOT NULL DEFAULT FALSE,
    full_name VARCHAR(255) NOT NULL,
    role VARCHAR(64) NOT NULL
);

CREATE TABLE car_models (
    id UUID PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    removed BOOLEAN NOT NULL DEFAULT FALSE,
    brand VARCHAR(255) NOT NULL,
    name VARCHAR(255) NOT NULL,
    body_type VARCHAR(64) NOT NULL,
    fuel_type VARCHAR(64) NOT NULL,
    engine_power_hp INTEGER NOT NULL,
    engine_volume_liters NUMERIC(10, 2) NOT NULL,
    transmission_type VARCHAR(64) NOT NULL,
    drive_type VARCHAR(64) NOT NULL,
    base_price NUMERIC(14, 2) NOT NULL
);

CREATE TABLE component_options (
    id UUID PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    removed BOOLEAN NOT NULL DEFAULT FALSE,
    type VARCHAR(64) NOT NULL,
    name VARCHAR(255) NOT NULL,
    price_delta NUMERIC(14, 2) NOT NULL
);

CREATE TABLE car_model_required_components (
    model_id UUID NOT NULL REFERENCES car_models(id),
    component_type VARCHAR(64) NOT NULL,
    PRIMARY KEY (model_id, component_type)
);

CREATE TABLE component_option_compatible_models (
    component_option_id UUID NOT NULL REFERENCES component_options(id),
    model_id UUID NOT NULL REFERENCES car_models(id),
    PRIMARY KEY (component_option_id, model_id)
);

CREATE TABLE car_model_base_component_options (
    model_id UUID NOT NULL REFERENCES car_models(id),
    component_type VARCHAR(64) NOT NULL,
    component_option_id UUID NOT NULL REFERENCES component_options(id),
    PRIMARY KEY (model_id, component_type)
);

CREATE TABLE cars (
    id UUID PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    removed BOOLEAN NOT NULL DEFAULT FALSE,
    model_id UUID NOT NULL REFERENCES car_models(id),
    color VARCHAR(255) NOT NULL,
    price NUMERIC(14, 2) NOT NULL,
    available BOOLEAN NOT NULL DEFAULT TRUE,
    test_drive_available BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE parts (
    id UUID PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    removed BOOLEAN NOT NULL DEFAULT FALSE,
    sku VARCHAR(255) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    price NUMERIC(14, 2) NOT NULL
);

CREATE TABLE part_compatible_models (
    part_id UUID NOT NULL REFERENCES parts(id),
    model_id UUID NOT NULL REFERENCES car_models(id),
    PRIMARY KEY (part_id, model_id)
);

CREATE TABLE in_stock_car_orders (
    id UUID PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    removed BOOLEAN NOT NULL DEFAULT FALSE,
    client_id UUID NOT NULL REFERENCES app_users(id),
    manager_id UUID NOT NULL REFERENCES app_users(id),
    car_id UUID NOT NULL REFERENCES cars(id),
    ordered_at TIMESTAMP NOT NULL,
    status VARCHAR(64) NOT NULL
);

CREATE TABLE custom_car_orders (
    id UUID PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    removed BOOLEAN NOT NULL DEFAULT FALSE,
    client_id UUID NOT NULL REFERENCES app_users(id),
    manager_id UUID NOT NULL REFERENCES app_users(id),
    model_id UUID NOT NULL REFERENCES car_models(id),
    total_price NUMERIC(14, 2) NOT NULL,
    ordered_at TIMESTAMP NOT NULL,
    status VARCHAR(64) NOT NULL
);

CREATE TABLE custom_order_components (
    custom_order_id UUID NOT NULL REFERENCES custom_car_orders(id),
    component_type VARCHAR(64) NOT NULL,
    component_option_id UUID NOT NULL REFERENCES component_options(id),
    PRIMARY KEY (custom_order_id, component_type)
);

CREATE TABLE test_drive_requests (
    id UUID PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    removed BOOLEAN NOT NULL DEFAULT FALSE,
    client_id UUID NOT NULL REFERENCES app_users(id),
    car_id UUID NOT NULL REFERENCES cars(id),
    starts_at TIMESTAMP NOT NULL
);

